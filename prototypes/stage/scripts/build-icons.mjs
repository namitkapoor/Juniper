// Builds src/about/stackIcons.js: only the Iconify icons the stack uses
// (Simple Icons brand marks + Lucide line glyphs), bundled, so nothing is
// fetched from the Iconify API at runtime. Run: node scripts/build-icons.mjs
import fs from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const si = require("@iconify-json/simple-icons/icons.json");
const lu = require("@iconify-json/lucide/icons.json");
const WANT = {
  "simple-icons": ["typescript", "react", "nextdotjs", "nodedotjs", "python", "threedotjs", "claude", "langflow", "googlecloud", "postgresql", "googlebigquery", "notion", "n8n", "vercel", "playwright", "figma", "adobeaftereffects", "blender", "unity", "csharp"],
  lucide: ["bot", "component", "layers", "book-open", "gamepad-2", "image", "file-text", "external-link", "moon"],
};
const out = {};
for (const [set, names] of Object.entries(WANT)) {
  const data = set === "lucide" ? lu : si;
  for (const n of names) {
    const ic = data.icons[n];
    if (!ic) throw new Error(`missing ${set}:${n}`);
    out[`${set}:${n}`] = { body: ic.body, w: ic.width ?? data.width ?? 24, h: ic.height ?? data.height ?? 24, line: set === "lucide" };
  }
}
fs.writeFileSync(new URL("../src/about/stackIcons.js", import.meta.url),
  `// GENERATED by scripts/build-icons.mjs from @iconify-json/simple-icons and @iconify-json/lucide. Do not edit.\nexport const ICONS = ${JSON.stringify(out, null, 0)};\n`);
console.log(Object.keys(out).length, "icons");
